/**
 * ③候補カードのオプション欄。
 *
 * オプションは `gate` に入れていない（`gate` のコメントの理由）ので、**オプションが
 * 違っていても候補として並ぶ**。並んだ候補が基準機と何が違うのかを言わなければ、
 * 現場は「型式が違うだけの同じもの」として受け取る。`MS3749-A-O25` と
 * `MS3749-A-O25/H` は仕様値が1つも違わず、差はオプションだけなので、
 * ここに出さないと画面上は完全に同じ2枚のカードになる。
 *
 * 出すのは事実（候補は何を持つか／基準機は何を持つか）までで、
 * 置換えの可否は書かない。コーティングの有無が問題になるかは設置環境で決まり、
 * センサ供給電源が要るかは接続先のセンサで決まる。どちらもアプリは知らない。
 *
 * 枠の色は、基準機が持つオプションを候補が持たないときだけ橙（`warn`）にする。
 * 供給型が必要な回路に非供給型を付ければセンサが動かないので、
 * 「失う側」は同じ重みで扱えない。逆に候補側にだけ付いている分は `info`。
 *
 * どちらもオプションを持たない組では枠を出さない（`MS3749-A-D45` ⇔
 * `MS3749-D-D45` がこれ）。「オプションなし ⇔ オプションなし」と書いた枠は
 * 情報を増やさず、本当に差がある枠と同じ場所を占める。
 */
function optionPanel(m, c) {
  const mo = m.specs?.option;
  const co = c.specs?.option;
  if (!mo?.length && !co?.length) return null;
  const same = sameOption(mo, co);
  const lost = !!mo?.length && !same;
  const none = 'オプションの指定なし';
  return {
    tone: same ? 'ok' : lost ? 'warn' : 'info',
    title: 'オプション',
    // `panelBox` は body を1つの span に入れるので、行の区切りは <br> で作る
    // （入れ子の span はフレックスの子にならず、1行に続けて流れてしまう）
    body: `この候補: ${esc(co?.length ? optionText(co) : none)}<br>`
      + `基準 ${esc(m.model)}: ${esc(mo?.length ? optionText(mo) : none)}`
      + (same ? '' : '<br>オプションは互換判定に使っていません。一致は候補の条件ではありません。'),
  };
}

