    const rows = [];
    const s = d.specs ?? {};
    if (s.inputResistance) rows.push({ label: '入力抵抗', value: s.inputResistance });
    // 第1出力にも specDefs の入力信号と同じ `formatSignal` を掛ける。
    // ここだけ仕様書の表記のままにすると、同じ仕様欄の中で表記が割れる
    // （MS3749-A-O25 で「入力 OPN.C. / 第1出力 オープンコレクタ」）
    if (s.output1Signal) rows.push({ label: '第1出力', value: formatSignal(s.output1Signal) });
    if (s.output1MaxFreqHz != null) {
      rows.push({ label: '第1出力 最大周波数', value: formatFreq(s.output1MaxFreqHz) });
    }
    if (s.output2Signal) {
      rows.push({ label: '第2出力', value: formatSignal(s.output2Signal) });
      if (s.output2MaxFreqHz != null) {
        rows.push({ label: '第2出力 最大周波数', value: formatFreq(s.output2MaxFreqHz) });
      }
    }
