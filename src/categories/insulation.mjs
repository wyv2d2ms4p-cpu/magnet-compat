/**
 * 絶縁変換器（パルスアイソレータ）。
 *
 * 入力パルスを絶縁したまま整形して出す機器で、判定材料は容量ではなく
 * **信号の種別**（入力・第1出力・第2出力）になる。接触器やインバータのような
 * 「大きい／小さい」の軸を持たないため、窓（`withinWindow`）も
 * `primaryStanding` も使わない。
 *
 * 登録してあるのは MTT MS3749 系の14件だけ。**型式コードから組み合わせを展開して
 * 増やさないこと。** MS3749 の型式は公式資料には型式コード表の組み合わせとしてしか
 * 存在せず、個別型式としての列挙が無いため、実在の根拠は資料の外にしかない。
 * `data/insulation.json` の `evidence` は側面ごとに出典が分かれていて、
 * 実在（`model`）と仕様（`dims` / `specs`）で系統が違う。
 *
 *   - 実在 … 現場写真（既登録2件）／社内予備品リストの画面（追加12件）
 *   - 仕様 … MTT 標準仕様書 MS3749（文書番号 MQDDK-110729-33 Rev.2.10）
 *
 * 仕様の出典は全14件が Rev.2.10 を指す。既登録2件は Rev.2.00 を引用していたが、
 * 現に取得できる版を指すべきなので更新した（両版で型式コード表に差は見つかっていない。
 * 仕様値は1つも変えていない）。
 *
 * **登録していない項目と、その理由（14件に共通なのでここに1度だけ書く）。**
 * データ側の `srcNote` に同じ文を14回書き写すと、②の出典行がそれだけで
 * 画面を埋める（既登録2件の `srcNote` が300字前後あり、実際に読みづらくなっていた）。
 *
 *   - 取付穴ピッチ（`holes`）… 仕様書に記載が無く、外形図PDF（別ファイル）が未取得
 *   - 入力抵抗 … 仕様書の「入力抵抗」欄は電圧入力型・ラインドライバ型・電流入力型
 *     のみの記載で、型式コード欄と p.3 接続図にある 3.3kΩ が同じ意味かを断定できない
 *   - 最大消費電力 … 電源と1出力/2出力で6通りに分かれ、判定にも表示にも使わない
 *   - ラインドライバ入力のターミネーション抵抗 120Ω … 判定にも表示にも使わない
 *   - 生産終了かどうか … MS3749 が現行品であることは確認できるが、
 *     個別の型式コードの終息は未調査。`discontinued` はキーごと不在
 *   - 在庫数 … 予備品リストには現在庫が載っているが、変動する値なので持たない。
 *     「棚にある」は復旧時間に直結する情報だが、データに持つと腐る。
 *     持つとしたら「予備品として登録された実績がある」という事実にとどめる形。判断は保留
 *
 * どれも `0` や空文字で埋めず、キーごと不在にしてある（README「データの約束」）。
 */
import { registerCategory } from '../core/registry.mjs';
import { preferTrue, ascending } from '../core/compat.mjs';
import { evidenceRank } from '../core/evidence.mjs';
import { esc, num } from '../core/util.mjs';

/**
 * 信号種別の一致。
 *
 * **値が無い側を「一致」に倒さない。** 片方でもキーを持たなければ false を返す。
 * `a === b` だけで書くと `undefined === undefined` が真になり、
 * 「どちらも入力信号を登録していないから一致」という、根拠の無い候補が
 * 静かに混ざる（CLAUDE.md「解析できないから一致とみなす」経路を作らない）。
 * 第2出力の「両方とも持たない」＝1出力型どうしは、これとは別に gate 側で扱う。
 */
function signalMatch(a, b) {
  if (typeof a !== 'string' || typeof b !== 'string') return false;
  return a === b;
}

/** 周波数の表示。仕様書は 100kHz / 200kHz と kHz で書いている。 */
function formatFreq(v) {
  return v >= 1000 ? `${num(v / 1000)}kHz` : `${num(v)}Hz`;
}

/**
 * オプションの表示文字列。
 *
 * **`code` だけでは現場に伝わらない。** 画面に「H」とだけ出ても、それが
 * コーティングなのかセンサ供給電源なのかが読めない。型式の末尾に現れる綴り
 * （`/H`）と、仕様書 p.1 のオプション表の文言を必ず並べて出す。
 * 複数指定（仕様書の発注例 `MS3749-A-D11/AT`）があり得るので配列を受ける。
 */
function optionText(list) {
  return list.map((o) => `/${o.code} ${o.text}`).join(' ・ ');
}

/** オプションの有無・内容が基準機と同じか（表示の出し分けにだけ使う。判定には使わない） */
function sameOption(a, b) {
  const key = (list) => (list ? list.map((o) => o.code).sort().join('') : '');
  return key(a) === key(b);
}

registerCategory({
  id: 'insulation',
  label: '絶縁変換器',
  group: 'signal',
  /**
   * 宣言するのは **14件すべてが必ず持つスペックだけ**。
   *
   * `specGrid`（②の仕様欄）は宣言された specDefs を値の有無に関わらず必ず描くので、
   * 型式によって有無が変わるスペックをここに置くと、持たない型式の画面に
   * 「第2出力 ―」という欄が残る。1出力型（型式コードの第2出力が未記入＝なし）に
   * 対して、この「―」は「該当なし」なのか「未登録」なのかを語れない。
   * 有無が変わるもの（第2出力・オプション）は下の `summary` に置き、
   * **持たない型式では欄そのものを出さない**。
   *
   * 宣言順は「人が見分けやすい順」。銘板の印字（IN / OUT1）と型式コードの並び
   * （電源・入力・第1出力）がどちらもこの順で、現場は端子番号と銘板から入る。
   * `summary` はこの続き（第2出力 → 電源電圧 → オプション）を描くので、
   * ②の仕様欄は上から銘板の並びのまま読める。
   *
   * **代償**：曖昧一致リストの識別材料（`distinguishingSpec`）は宣言順の先頭から
   * 「値が割れている最初のスペック」を選ぶため、ここから外した第2出力・電源電圧・
   * オプションは識別材料に選ばれない。いま登録されている14件に `normLoose` で
   * 同じ綴りになる組は無く、曖昧一致リストにこの4件が並ぶ経路は無い。
   * 将来そういう組が入ったときは、`tools/verify-data.mjs` の
   * 「検索で同じ綴りになる型式に見分ける材料がある」が**黙って通らずに落ちる**ので、
   * そこで宣言を見直すこと。
   *
   * 主スペック（`primary`）は暫定で入力信号。カード右上とヘッダに出るのは
   * この値で、置換えの可否をいちばん左右するのが「その信号を受けられるか」だから。
   */
  specDefs: [
    { key: 'inputSignal', label: '入力信号', primary: true },
    { key: 'output1Signal', label: '第1出力' },
    { key: 'output1MaxFreqHz', label: '第1出力 最大周波数', unit: 'Hz', format: formatFreq },
  ],
  /**
   * 主スペックの入力信号は大小を判定しない。
   *
   * `inputSignal` は信号種別の名前で、「無電圧接点・オープンコレクタ」と
   * 「ラインドライバ」のあいだに大小は無い。順序が無いものに
   * `numericStanding` を当てると、比較できない組を無理やり2値に倒すことになる。
   * 判定しないカテゴリなので `standingNote` も持たない（出番が無い）。
   */
  primaryStanding: () => null,
  /**
   * 候補の必要条件は、入力信号・第1出力・第2出力の3つが一致すること。
   *
   * 入力が違えば信号を受けられない。第1出力は型式コード上かならず指定される
   * （＝必ず存在する）出力なので、違えば受け側が動かない可能性が高い。
   * 第2出力は「なし」があり得るため、**両方が持つときだけ一致を要求し、
   * 片方だけが持つ組は候補にしない**。1出力型を2出力型の代わりに挿すと
   * 使っていた出力が消え、逆向きは端子が余るだけに見えて実際には
   * 端子割付が変わる。どちらも「そのまま挿せる」ではない。
   *
   * 窓（`withinWindow`）は使わない。この判定に大小の概念が無いため。
   *
   * 後継品バイパス（`a.id === m.successorId`）は置いていない。生産終了・後継の
   * 情報を MTT について調べておらず、`data/insulation.json` に `successorId` を
   * 持つレコードが1件も無いので、いま書いても一度も通らない経路になる。
   * 「後継指定なら信号種別が違っても候補に出してよいか」は、実例が出てから
   * その実例と一緒に決める。
   *
   * ---
   * **オプション（`specs.option`）を判定に入れない理由（依頼者の判断）**
   *
   * `/A`〜`/F` のセンサ供給電源は2線式・3線式センサへ電源を供給する機能で、
   * 入出力の能力そのものにあたる。供給型が必要な回路に非供給型を付ければ
   * センサが動かないので、本来は判定材料になり得る。それでも入れないのは:
   *
   * 1. 該当が14件中1件（`MS3749-A-D33/D`）しかなく、判定の正しさを検査で固定できない。
   *    候補が0件のまま「PASS」と出る検査になる（CLAUDE.md が禁じている形）
   * 2. `/A`〜`/F` の6種が揃うまで、どれとどれが代替可能かを決められない。
   *    24V と 12V、2線式と3線式は互換ではない
   * 3. 表示があれば現場は画面で気づける。②の仕様欄と③の候補カードの両方に出している
   *
   * **該当データが増えた時点で再検討すること。** 判定に入れるなら、
   * 「コーティング（`/H`）は違っても置換えできる」「センサ供給電源は違うと使えない」
   * のように**オプションの種別ごとに扱いが変わる**ので、`option` の一致では書けない。
   *
   * ---
   * **保留した課題：OUT1 と OUT2 が入れ替わった機器を候補に出したい（未実装）**
   *
   * 依頼者から要求があったが、今回も実装していない。次にこの gate を触る人へ:
   *
   * 1. これは判定の意味を「そのまま挿せる」から「配線を直せば使える」へ
   *    広げる変更になる。いまの候補は前者だけを指している。
   * 2. MS3749 では第1出力にラインドライバを選べない（型式コードの第1出力は
   *    1〜4 のみで、5＝ラインドライバ・パルスは第2出力専用）。つまり
   *    「OUT1 がラインドライバ、OUT2 がオープンコレクタ」という入れ替え品は
   *    同シリーズ内に存在せず、いま実装しても対象は0件になる。
   *    追加した12件でも第1出力にラインドライバを持つ型式は1件も無く、
   *    **対象は依然0件のまま**。
   * 3. 端子割付が出力種別で変わる。第2出力がラインドライバのときは
   *    端子⑥⑦⑧が Y / Z / COM になる（仕様書 p.2）。入れ替えは盤内の
   *    配線変更を伴うので、「候補に出す」と「そのまま置換えられる」が一致しない。
   * 4. 応答周波数が出力種別で違う（オープンコレクタ 100kHz /
   *    ラインドライバ 200kHz）。入れ替えの可否は種別だけでなく周波数まで
   *    見ないと決まらない。
   *
   * 実装するなら完全一致の候補とは別ゾーンに分け、配線変更が要ることを
   * 明示すること（③の2分割＝`zoneHead` が前例）。同じ列に混ぜると、
   * そのまま挿せる候補と見分けがつかなくなる。
   */
  gate(a, m) {
    if (!signalMatch(a.specs?.inputSignal, m.specs?.inputSignal)) return false;
    if (!signalMatch(a.specs?.output1Signal, m.specs?.output1Signal)) return false;
    const a2 = a.specs?.output2Signal;
    const m2 = m.specs?.output2Signal;
    // 両方とも第2出力を持たない（1出力型どうし）なら、第2出力は判定材料にならない
    if (a2 == null && m2 == null) return true;
    return signalMatch(a2, m2);
  },
  rank(a, b) {
    return (
      preferTrue(a.mountingMatch, b.mountingMatch) ||
      preferTrue(a.sameMaker, b.sameMaker) ||
      evidenceRank(a) - evidenceRank(b) ||
      ascending(a.diff, b.diff)
    );
  },
  /**
   * ②確認画面の仕様欄のうち、**持つ型式と持たない型式がある**もの。
   *
   * `specGrid` は specDefs を先に描いてからこれを続けるので、返す順がそのまま
   * 画面の並びになる。第2出力 → 電源電圧 → オプションの順にしてあるのは、
   * specDefs（入力信号・第1出力・第1出力 最大周波数）の続きとして
   * 銘板と型式コードの並び（電源・入力・第1出力・第2出力・オプション）に沿うため。
   *
   * **持たないものは行ごと返さない。** `{ value: '―' }` を返すと、
   * 1出力型の「第2出力なし」とデータ未登録が同じ見た目になる。
   * `option` を空配列で持たせない約束（`tools/schema-map.mjs`）も同じ理由。
   */
  summary(d) {
    const rows = [];
    const out2 = d.specs?.output2Signal;
    if (out2) {
      rows.push({ label: '第2出力', value: out2 });
      const f = d.specs?.output2MaxFreqHz;
      if (f != null) rows.push({ label: '第2出力 最大周波数', value: formatFreq(f) });
    }
    if (d.specs?.powerSupply) rows.push({ label: '電源電圧', value: d.specs.powerSupply });
    const opt = d.specs?.option;
    if (opt?.length) rows.push({ label: 'オプション', value: optionText(opt) });
    return rows;
  },
  /**
   * ③候補カードのオプション欄。
   *
   * オプションは `gate` に入れていない（上の理由）ので、**オプションが違っていても
   * 候補として並ぶ**。並んだ候補が基準機と何が違うのかを言わなければ、
   * 現場は「型式が違うだけの同じもの」として受け取る。`MS3749-A-O25` と
   * `MS3749-A-O25/H` は仕様値が1つも違わず、差はオプションだけなので、
   * ここに出さないと画面上は完全に同じ2枚のカードになる。
   *
   * 出すのは事実（候補は何を持つか／基準機は何を持つか）までで、
   * 置換えの可否は書かない。コーティングの有無が問題になるかは設置環境で決まり、
   * センサ供給電源が要るかは接続先のセンサで決まる。どちらもアプリは知らない。
   *
   * 枠の色は、基準機が持つオプションを候補が持たないときだけ橙（`warn`）にする。
   * 供給型が必要な回路に非供給型を付ければセンサが動かないので、
   * 「失う側」は同じ重みで扱えない。逆に候補側にだけ付いている分は `info`。
   *
   * どちらもオプションを持たない組では枠を出さない（`MS3749-A-D45` ⇔
   * `MS3749-D-D45` がこれ）。「オプションなし ⇔ オプションなし」と書いた枠は
   * 情報を増やさず、本当に差がある枠と同じ場所を占める。
   */
  detailPanels(m, c) {
    const mo = m.specs?.option;
    const co = c.specs?.option;
    if (!mo?.length && !co?.length) return [];
    const same = sameOption(mo, co);
    const lost = !!mo?.length && !same;
    const none = 'オプションの指定なし';
    return [{
      tone: same ? 'ok' : lost ? 'warn' : 'info',
      title: 'オプション',
      // `panelBox` は body を1つの span に入れるので、行の区切りは <br> で作る
      // （入れ子の span はフレックスの子にならず、1行に続けて流れてしまう）
      body: `この候補: ${esc(co?.length ? optionText(co) : none)}<br>`
        + `基準 ${esc(m.model)}: ${esc(mo?.length ? optionText(mo) : none)}`
        + (same ? '' : '<br>オプションは互換判定に使っていません。一致は候補の条件ではありません。'),
    }];
  },
  /**
   * 候補0件のときの説明。
   *
   * 語るのは「その画面で何が落ちたか」ではなく「候補の必要条件」。
   * `emptyNote(m)` は基準機しか受け取らないので、**アプリはその画面で
   * どの条件が効いたかを実行時に知らない**（`src/categories/sensor-common.mjs`
   * の `sensorEmptyNote` と同じ制約）。起きたことを語ると、実際には
   * 別の条件で落ちた画面で偽になる。
   *
   * 見出しで「登録されていません」と断定しないのも同じ理由。0件は登録の
   * 欠落とは限らず、登録済みの型式が判定で外れただけのこともある。
   * この語は検索画面が「実在確認済みのデータが未登録です」の意味で
   * 使っている（`src/core/app.mjs`）。
   *
   * gate を変えたらこの文面も追随させること。名指ししている3条件が
   * `gate` の必要条件でなくなった瞬間、文面だけが残る。
   * オプションを名指ししていないのは、`gate` が見ていないから。
   * 見ていない条件を0件の理由として名乗らない（インバータの0件20件で起きた形）。
   */
  emptyNote() {
    return `<b class="amber">互換品候補は見つかりませんでした。</b>
      <div>このカテゴリが候補に出すのは、入力信号と第1出力の種別が一致し、
      第2出力も種別が一致する型式だけです。第2出力を一方だけが持つ組は候補にしません。
      この型式では、それを満たす登録型式がありませんでした。
      どの条件で外れたかはこの画面では判別できません。</div>`;
  },
});
